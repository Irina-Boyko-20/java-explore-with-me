package ru.practicum.exception;

/**
 * Исключение, указывающее на конфликтное состояние при выполнении запрошенной операции.
 * <p>
 * Используется в сценариях, когда запрошенная операция не может быть выполнена
 * из-за конфликта с текущим состоянием системы, бизнес-правилами или ограничениями
 * целостности данных. Означает, что запрос корректен, но не может быть обработан
 * в текущих условиях.
 * </p>
 *
 * <p>
 * Автоматически обрабатывается {@link GlobalExceptionHandler} и преобразуется
 * в HTTP-ответ со статусом 409 (Conflict) с соответствующим сообщением об ошибке.
 * </p>
 */
public class ConflictException extends RuntimeException {

    /**
     * Создает новое исключение с указанным сообщением об ошибке.
     *
     * @param message детальное сообщение об ошибке, описывающее природу конфликта
     *                и условия его возникновения.
     *                Пример: "Cannot publish event because it's not in the correct state: PENDING"
     */
    public ConflictException(String message) {
        super(message);
    }
}
