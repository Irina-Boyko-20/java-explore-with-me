package ru.practicum.exception;

/**
 * Исключение, указывающее на отсутствие прав доступа для выполнения запрошенной операции.
 * <p>
 * Используется в сценариях, когда аутентифицированный пользователь пытается выполнить
 * операцию, для которой у него недостаточно прав.
 * В отличие от аутентификации, пользователь идентифицирован, но ему отказано в доступе.
 * </p>
 *
 * <p>
 * Автоматически обрабатывается {@link GlobalExceptionHandler} и преобразуется
 * в HTTP-ответ со статусом 403 (Forbidden) с соответствующим сообщением об ошибке.
 * </p>
 */
public class ForbiddenException extends RuntimeException {

    /**
     * Создает новое исключение с указанным сообщением об ошибке.
     *
     * @param message детальное сообщение об ошибке, объясняющее причину запрета доступа.
     *                Пример: "Only the event initiator can modify this event"
     */
    public ForbiddenException(String message) {
        super(message);
    }
}
