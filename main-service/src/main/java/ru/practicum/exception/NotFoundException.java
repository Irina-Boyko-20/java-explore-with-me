package ru.practicum.exception;

/**
 * Исключение, указывающее на то, что запрашиваемый ресурс не был найден в системе.
 * <p>
 * Используется в сценариях, когда выполняется попытка доступа к несуществующему
 * ресурсу, такому как пользователь, событие, категория, запрос на участие и т.д.
 * Генерируется сервисным слоем при проверке существования сущностей по идентификаторам.
 * </p>
 *
 * <p>
 * Автоматически обрабатывается {@link GlobalExceptionHandler} и преобразуется
 * в HTTP-ответ со статусом 404 (Not Found) с соответствующим сообщением об ошибке.
 * </p>
 */
public class NotFoundException extends RuntimeException {

    /**
     * Создает новое исключение с указанным сообщением об ошибке.
     *
     * @param message детальное сообщение об ошибке, описывающее какой ресурс
     *                не был найден и при каких обстоятельствах.
     *                Пример: "User with id=123 was not found"
     */
    public NotFoundException(String message) {
        super(message);
    }
}
