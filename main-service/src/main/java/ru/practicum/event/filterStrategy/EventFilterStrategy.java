package ru.practicum.event.filterStrategy;

import org.springframework.data.jpa.domain.Specification;
import ru.practicum.event.entity.Event;

/**
 * Стратегия для построения спецификаций фильтрации событий.
 * <p>
 * Определяет контракт для создания {@link Specification} объектов, которые
 * используются для динамического построения запросов к событиям на основе
 * различных критериев фильтрации. Каждая реализация представляет собой
 * отдельную стратегию фильтрации с определенной бизнес-логикой.
 * </p>
 *
 * <p>
 * Параметры передаются в виде массива Object для обеспечения гибкости
 * различных стратегий фильтрации.
 * </p>
 */
public interface EventFilterStrategy {

    /**
     * Создает спецификацию для фильтрации событий на основе переданных параметров.
     * <p>
     * Каждая реализация интерфейса определяет собственную логику построения
     * предикатов фильтрации в зависимости от бизнес-требований.
     * </p>
     *
     * @param params массив параметров фильтрации. Структура и типы параметров
     *               определяются конкретной реализацией стратегии.
     * @return спецификация {@link Specification} для использования в запросах
     *         JPA Specification. Если параметры не позволяют построить валидную
     *         спецификацию, может возвращать {@code null}.
     */
    Specification<Event> apply(Object... params);
}
