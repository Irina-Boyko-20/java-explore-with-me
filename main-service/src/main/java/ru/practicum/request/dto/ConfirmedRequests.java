package ru.practicum.request.dto;

import lombok.AllArgsConstructor;
import lombok.Setter;
import lombok.Getter;
import lombok.AccessLevel;
import lombok.experimental.FieldDefaults;

/**
 * Вспомогательный класс для представления агрегированных данных о подтвержденных запросах на участие.
 * <p>
 * Используется в качестве проекции результатов SQL-запросов для подсчета количества
 * подтвержденных запросов на участие для каждого события. Оптимизирует выполнение
 * агрегирующих запросов к базе данных.
 * </p>
 *
 * <p>
 * Применяется в сценариях, когда необходимо получить количество подтвержденных
 * участников для нескольких событий одновременно, без загрузки полных данных
 * о каждом запросе на участие.
 * </p>
 *
 * <p>
 * Создается через конструктор с параметрами и используется преимущественно
 * в репозиторных методах с нативными запросами или проекциями Spring Data JPA.
 * </p>
 */

@AllArgsConstructor
@Setter
@Getter
@FieldDefaults(level = AccessLevel.PRIVATE)
public class ConfirmedRequests {

    /**
     * Количество подтвержденных запросов на участие.
     */
    long count;

    /**
     * Идентификатор события, для которого подсчитаны подтвержденные запросы.
     */
    Long event;
}
